import { chromium } from 'playwright-core'
import { access, readFile, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const url = process.argv[2] ?? 'http://127.0.0.1:5173'
const candidates = process.platform === 'win32' ? ['C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'] : ['/usr/bin/google-chrome', '/usr/bin/chromium']
let executablePath
for (const path of candidates) { try { await access(path); executablePath = path; break } catch {} }
if (!executablePath) throw new Error('Chrome or Edge is required.')
const browser = await chromium.launch({ executablePath, headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(url, { waitUntil: 'networkidle' })
  const ids = await page.evaluate(async () => {
    const { createManuscriptFixture } = await import('/scripts/fixtures/manuscript-figure.ts')
    const { FigureEditor } = await import('/src/figure-editor.ts')
    const fixture = createManuscriptFixture()
    window.__manuscriptFigure = new FigureEditor({ ...fixture, genes: () => fixture.genes, chromosomes: () => new Map([['chr1', 3000000]]), restoreSources: async () => fixture.sources, relinkSource: async () => undefined, onClose: () => {} })
    window.__manuscriptFigure.show()
    return { column: fixture.document.columns[0].id, matrix: fixture.document.rows.find((row) => row.trackIds[0] === 'matrix-0').id, gene: fixture.document.rows.find((row) => row.trackIds[0] === 'reference-genes').id, pro: fixture.document.rows.find((row) => row.trackIds[0] === 'pro-0').id }
  })
  const ready = () => page.waitForFunction(() => document.querySelector('.figure-editor [data-role="status"]')?.textContent.includes('mm'))
  await ready()
  assert.equal(await page.locator('.fe-page [data-fe-legend="matrix"]').count(), 1)
  // Export the preset example for visual inspection at print resolution.
  await page.locator('[data-action="export-png"]').click()
  const [example] = await Promise.all([page.waitForEvent('download'), page.locator('.fe-confirm button[value="300"]').click()])
  await writeFile('dist/figure-manuscript-example.png', await readFile(await example.path()))
  await page.locator(`.fe-sidebar [data-select="row"][data-row="${ids.matrix}"]`).click()
  const palette = page.locator(`details[data-detail="cell-${ids.column}"] [data-edit="cell-matrix-palette"]`)
  assert.equal(await palette.inputValue(), 'custom')
  await palette.selectOption('blue-black'); await ready()
  assert.equal(await page.evaluate(({ column, matrix }) => window.__manuscriptFigure.currentDocument.columns.find((item) => item.id === column).styles[matrix].appearance.matrixColors, ids), undefined)
  await page.locator('[data-action="undo"]').click()
  const commit = async (locator, value) => { await locator.fill(value); await locator.press('Tab'); await ready() }
  await page.locator(`.fe-sidebar [data-select="column"][data-column="${ids.column}"]`).click()
  await commit(page.locator('[data-edit="column-weight"]'), '1.5')
  await page.locator('[data-action="column-right"]').click()
  assert.equal(await page.evaluate(() => window.__manuscriptFigure.currentDocument.columns[1].widthWeight), 1.5)
  await page.locator('[data-action="undo"]').click()
  await page.locator('[data-action="undo"]').click()
  await page.locator(`.fe-sidebar [data-select="row"][data-row="${ids.gene}"]`).click()
  const cell = () => page.locator(`details[data-detail="cell-${ids.column}"]`)
  await cell().locator('.fe-properties').filter({ hasText: 'Gene models' }).locator('summary').click()
  await commit(cell().locator('[data-property="geneFontPt"]'), '6')
  await commit(cell().locator('[data-property="cdsHeightMm"]'), '0.875')
  await commit(cell().locator('[data-property="geneNames"]'), 'GENE_A')
  await cell().locator('[data-action="copy-cell-style"]').click()
  assert.equal(await page.locator('.fe-page text').filter({ hasText: /^GENE_A$/ }).count(), 3)
  assert.equal(await page.locator('.fe-page text').filter({ hasText: /^GENE_B$/ }).count(), 0)
  await page.locator(`.fe-sidebar [data-select="row"][data-row="${ids.pro}"]`).click()
  await page.locator(`details[data-detail="cell-${ids.column}"] [data-edit="cell-scale-mode"]`).selectOption('fixed')
  const pro = () => page.locator(`details[data-detail="cell-${ids.column}"]`)
  await commit(pro().locator('[data-edit="cell-scale-min"]'), '-100')
  await commit(pro().locator('[data-edit="cell-scale-max"]'), '100')
  await commit(pro().locator('[data-edit="section-max"][data-section="1100000"]'), '25')
  assert.equal(await page.locator(`.fe-page [data-fe-column="${ids.column}"] [data-scale-start="1100000"][data-scale-max="25"]`).count(), 1)
  await page.locator('.fe-sidebar [data-select="page"]').click()
  await page.locator('.fe-inspector .fe-properties').filter({ hasText: 'Ruler' }).locator('summary').click()
  await commit(page.locator('[data-property="scaleBarBp"]'), '20000')
  assert.equal(await page.locator('.fe-page text').filter({ hasText: /^20 kb$/ }).count(), 3)
  const [saved] = await Promise.all([page.waitForEvent('download'), page.locator('[data-action="save"]').click()])
  const project = JSON.parse(await readFile(await saved.path(), 'utf8'))
  assert.equal(project.schemaVersion, 2)
  assert.equal(project.columns.length, 3)
  assert.equal(project.columns[0].styles[ids.gene].appearance.cdsHeightMm, 0.875)
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.locator('[data-action="open"]').click()])
  await chooser.setFiles(await saved.path())
  await ready()
  assert.equal(await page.locator('.fe-page text').filter({ hasText: /^20 kb$/ }).count(), 3)
  const [svgDownload] = await Promise.all([page.waitForEvent('download'), page.locator('[data-action="export-svg"]').click()])
  const svg = await readFile(await svgDownload.path(), 'utf8')
  assert(svg.includes('data-scale-max="25"') && svg.includes('&quot;scaleBarBp&quot;:20000'))
  const [svgChooser] = await Promise.all([page.waitForEvent('filechooser'), page.locator('[data-action="open"]').click()])
  await svgChooser.setFiles(await svgDownload.path())
  await ready()
  assert.equal(await page.locator('.fe-page text').filter({ hasText: /^GENE_A$/ }).count(), 3)
  assert.equal(await page.locator('.fe-page text').filter({ hasText: /^20 kb$/ }).count(), 3)
  await page.locator('[data-action="zoom-fit"]').click()
  await page.screenshot({ path: 'dist/figure-manuscript-ui.png' })
  assert.deepEqual(errors, [])
  console.log('Manuscript Figure Editor: 3 conditions, geometry, genes, section scales, rulers, undo, project reopen, SVG and 300-DPI PNG passed.')
} finally { await browser.close() }
